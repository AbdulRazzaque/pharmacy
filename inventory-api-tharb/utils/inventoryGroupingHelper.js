const mongoose = require('mongoose');
const moment = require('moment');

/**
 * Normalizes an expiry date to UTC midnight for the calendar date (YYYY-MM-DD 00:00:00.000Z).
 * Corrects timezone offsets (e.g. UTC+3 midnight saving as 21:00Z on previous day)
 * and 5-digit typo years (e.g. 20230 -> 2030).
 */
function normalizeExpiryDate(expiry) {
  if (!expiry) return null;
  if (typeof expiry === 'string') {
    expiry = expiry.trim();
    if (!expiry) return null;
  }

  let d;
  if (expiry instanceof Date) {
    d = new Date(expiry.getTime());
  } else if (typeof expiry === 'string') {
    // Check if DD/MM/YYYY or DD-MM-YYYY format
    if (/^\d{1,2}[\/-]\d{1,2}[\/-]\d{4,5}$/.test(expiry)) {
      const parts = expiry.split(/[\/-]/);
      let day = parseInt(parts[0], 10);
      let month = parseInt(parts[1], 10);
      let year = parseInt(parts[2], 10);
      if (year > 2100) {
        const s = String(year);
        if (s.startsWith('20') && s.length === 5) {
          year = parseInt('20' + s.slice(3), 10);
        }
      }
      return new Date(Date.UTC(year, month - 1, day, 0, 0, 0, 0));
    }
    // Check for 5-digit typo year in ISO string, e.g. "20230-06-28" or "+020230"
    let cleanStr = expiry.replace(/^\+0*/, '');
    const match5 = cleanStr.match(/^(\d{5})-(.*)/);
    if (match5) {
      const s = match5[1];
      if (s.startsWith('20')) {
        const fixedYear = '20' + s.slice(3);
        cleanStr = fixedYear + '-' + match5[2];
      }
    }
    d = new Date(cleanStr);
  } else {
    d = new Date(expiry);
  }

  if (isNaN(d.getTime())) return null;

  let year = d.getUTCFullYear();
  if (year > 2100) {
    const s = String(year);
    if (s.startsWith('20') && s.length === 5) {
      year = parseInt('20' + s.slice(3), 10);
    }
  }

  let month = d.getUTCMonth();
  let date = d.getUTCDate();

  // If hours is >= 20, it was generated by local UTC+3 midnight offset (e.g. 21:00Z of previous day)
  if (d.getUTCHours() >= 20) {
    const nextDay = new Date(Date.UTC(year, month, date + 1));
    year = nextDay.getUTCFullYear();
    month = nextDay.getUTCMonth();
    date = nextDay.getUTCDate();
  }

  return new Date(Date.UTC(year, month, date, 0, 0, 0, 0));
}

/**
 * Returns a stable calendar date key: YYYY-MM-DD or 'no-expiry'
 */
function getExpiryKey(expiry) {
  const norm = normalizeExpiryDate(expiry);
  return norm ? norm.toISOString().slice(0, 10) : 'no-expiry';
}

/**
 * Returns a MongoDB query range for the entire calendar day of the normalized expiry date
 */
function buildExpiryDateRange(normalizedExpiry) {
  if (!normalizedExpiry) {
    return { $in: [null, undefined] };
  }
  const norm = normalizeExpiryDate(normalizedExpiry);
  if (!norm) {
    return { $in: [null, undefined] };
  }
  const start = new Date(norm.getTime());
  start.setUTCHours(0, 0, 0, 0);
  const end = new Date(norm.getTime());
  end.setUTCHours(23, 59, 59, 999);
  return { $gte: start, $lte: end };
}

/**
 * Builds a deterministic group identifier
 */
function buildLogicalGroupKey(productId, expiry, locationId = null) {
  const pId = String(productId || '');
  const expKey = getExpiryKey(expiry);
  const locKey = locationId ? `_${String(locationId)}` : '';
  return `group_${pId}_${expKey}${locKey}`;
}

/**
 * Groups an array of StockBalance records for a product into consolidated logical inventory display rows.
 * Preserves all underlying batch lot details while providing authoritative consolidated quantities.
 */
function groupStockBalances(balances = [], productDoc = {}) {
  const pId = String(productDoc._id || (balances[0] && balances[0].productId) || '');
  const authorSellingPrice = Number(productDoc.sellingPrice || 0);

  const groupMap = new Map();

  for (const b of balances) {
    const normExp = normalizeExpiryDate(b.expiry);
    const expKey = getExpiryKey(b.expiry);
    const locId = b.locationId ? String(b.locationId) : null;
    const groupKey = buildLogicalGroupKey(pId, normExp, locId);

    const bQty = Number(b.quantity) || 0;
    const bPurchasing = Number(b.purchasingPrice) || 0;
    const bSelling = Number(b.sellingPrice) || 0;
    const cleanBatch = (b.batchNumber || '').trim();

    const batchDetail = {
      _id: b._id,
      stockBalanceId: b._id,
      batchNumber: cleanBatch,
      quantity: bQty,
      expiry: normExp || b.expiry,
      purchasingPrice: bPurchasing,
      sellingPrice: authorSellingPrice > 0 ? authorSellingPrice : bSelling,
      locationId: b.locationId || null,
      createdAt: b.createdAt
    };

    if (!groupMap.has(groupKey)) {
      groupMap.set(groupKey, {
        _id: b._id, // default primary _id for backward compatibility
        groupId: groupKey,
        productId: productDoc._id || b.productId,
        name: productDoc.name || '',
        companyName: productDoc.companyName || '',
        type: productDoc.type || '',
        unit: productDoc.unit || '',
        slug: productDoc.slug || '',
        expiry: normExp,
        expiryKey: expKey,
        expiryFormatted: normExp ? moment(normExp).format('DD/MM/YYYY') : '',
        locationId: b.locationId || null,
        quantity: bQty,
        purchasingPrice: bPurchasing,
        sellingPrice: authorSellingPrice > 0 ? authorSellingPrice : bSelling,
        batches: [batchDetail],
        stockBalanceIds: [b._id],
        primaryStockBalanceId: b._id,
        batchNumber: cleanBatch
      });
    } else {
      const g = groupMap.get(groupKey);
      g.quantity += bQty;
      g.batches.push(batchDetail);
      g.stockBalanceIds.push(b._id);

      // Prefer primary balance with highest quantity
      const primaryBal = g.batches.reduce((prev, curr) => (curr.quantity > prev.quantity ? curr : prev), g.batches[0]);
      g._id = primaryBal._id;
      g.primaryStockBalanceId = primaryBal._id;

      // Combine batch labels for display
      const distinctBatches = Array.from(new Set(g.batches.map(bt => bt.batchNumber).filter(Boolean)));
      if (distinctBatches.length > 0) {
        g.batchNumber = distinctBatches.join(', ');
      }

      if (!g.purchasingPrice && bPurchasing) {
        g.purchasingPrice = bPurchasing;
      }
    }
  }

  return Array.from(groupMap.values());
}

/**
 * Resolves eligible underlying StockBalance records for a requested stock out item.
 * Supports:
 * - Specific stockBalanceIds array
 * - Group resolution by (productId, expiry)
 * - Single stockBalanceId with same-expiry pooling
 * - Fallback to FEFO across all batches if unbatched
 */
async function resolveEligibleBalances({
  productId,
  expiry = null,
  stockBalanceId = null,
  stockBalanceIds = [],
  batchNumber = '',
  locationId = null,
  session = null,
  StockBalanceModel = null
}) {
  const StockBalance = StockBalanceModel || require('../models/StockBalanceModule');
  const pId = new mongoose.Types.ObjectId(String(productId));

  let eligibleBalances = [];

  // 1. If explicit stockBalanceIds array provided
  if (Array.isArray(stockBalanceIds) && stockBalanceIds.length > 0) {
    const validIds = stockBalanceIds.filter(id => mongoose.Types.ObjectId.isValid(id)).map(id => new mongoose.Types.ObjectId(String(id)));
    if (validIds.length > 0) {
      let q = StockBalance.find({
        _id: { $in: validIds },
        productId: pId,
        quantity: { $gt: 0 }
      }).sort({ expiry: 1, createdAt: 1 });
      if (session) q = q.session(session);
      eligibleBalances = await q;
    }
  }

  // 2. If single stockBalanceId provided
  if (eligibleBalances.length === 0 && stockBalanceId && mongoose.Types.ObjectId.isValid(stockBalanceId)) {
    let q = StockBalance.findOne({
      _id: new mongoose.Types.ObjectId(String(stockBalanceId)),
      productId: pId
    });
    if (session) q = q.session(session);
    const primaryBal = await q;

    if (primaryBal) {
      // Find all sibling balances sharing the exact same normalized calendar expiry (and location if present)
      const normExp = normalizeExpiryDate(primaryBal.expiry || expiry);
      const filter = {
        productId: pId,
        expiry: buildExpiryDateRange(normExp),
        quantity: { $gt: 0 }
      };
      if (primaryBal.locationId) {
        filter.locationId = primaryBal.locationId;
      }

      let siblingQuery = StockBalance.find(filter).sort({ createdAt: 1 });
      if (session) siblingQuery = siblingQuery.session(session);
      eligibleBalances = await siblingQuery;
    }
  }

  // 3. If normalized expiry date provided
  if (eligibleBalances.length === 0 && expiry) {
    const normExp = normalizeExpiryDate(expiry);
    const filter = {
      productId: pId,
      expiry: buildExpiryDateRange(normExp),
      quantity: { $gt: 0 }
    };
    if (locationId && mongoose.Types.ObjectId.isValid(locationId)) {
      filter.locationId = new mongoose.Types.ObjectId(String(locationId));
    }

    let q = StockBalance.find(filter).sort({ createdAt: 1 });
    if (session) q = q.session(session);
    eligibleBalances = await q;
  }

  // 4. Fallback: FEFO across all available batches for this product
  if (eligibleBalances.length === 0 && !expiry && !stockBalanceId) {
    const filter = {
      productId: pId,
      quantity: { $gt: 0 }
    };
    if (locationId && mongoose.Types.ObjectId.isValid(locationId)) {
      filter.locationId = new mongoose.Types.ObjectId(String(locationId));
    }
    let q = StockBalance.find(filter).sort({ expiry: 1, createdAt: 1 });
    if (session) q = q.session(session);
    eligibleBalances = await q;
  }

  const totalAvailable = eligibleBalances.reduce((sum, b) => sum + (Number(b.quantity) || 0), 0);

  return {
    eligibleBalances,
    totalAvailable
  };
}

module.exports = {
  normalizeExpiryDate,
  getExpiryKey,
  buildExpiryDateRange,
  buildLogicalGroupKey,
  groupStockBalances,
  resolveEligibleBalances
};
